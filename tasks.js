/* ============ Тапсырма генераторлары (2-сынып) ============ */
const ri=(a,b)=>a+Math.floor(Math.random()*(b-a+1));
const pick=a=>a[Math.floor(Math.random()*a.length)];
function shuffle(a){a=a.slice();for(let i=a.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[a[i],a[j]]=[a[j],a[i]]}return a}
function sample(a,n){return shuffle(a).slice(0,n)}
const rep=(x,n)=>Array(n).fill(x).join(" + ");

function num(pre,post,a,e){return {k:"num",pre,post,a,e,key:pre+"|"+post}}
function mc(q,a,w,e,quote){return {k:"mc",q,a,opts:shuffle([a,...w]),e,quote,key:q+"|"+(quote||"")+"|"+a}}
function mcFixed(q,a,opts,e,quote){return {k:"mc",q,a,opts:opts.slice(),e,quote,key:q+"|"+(quote||"")+"|"+a}}
function sign(x,y){return x>y?">":x<y?"<":"="}
function cmp(l,r,lv,rv,e){const s=sign(lv,rv);return mcFixed("Қай белгі сәйкес келеді?",s,[">","<","="],e+` Сондықтан: ${l} ${s} ${r}.`,`${l}   ?   ${r}`)}

